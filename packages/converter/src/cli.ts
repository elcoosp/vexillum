/**
 * CLI: converts the badge collection HTML into packages/badges sources.
 *
 * Usage: tsx src/cli.ts <input.html> <packages/badges/src>
 */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { basename, join, resolve } from "node:path";
import { convert } from "./index";

const [inputArg, outArg] = process.argv.slice(2);
if (!inputArg || !outArg) {
  console.error("usage: tsx src/cli.ts <input.html> <badges-src-dir>");
  process.exit(1);
}

const input = resolve(inputArg);
const out = resolve(outArg);
const html = readFileSync(input, "utf8");
const result = convert(html);

// per-collection dirs
for (const v of result.variants) {
  const dir = join(out, v.collectionSlug);
  mkdirSync(dir, { recursive: true });
  writeFileSync(join(dir, `${v.id}.tsx`), v.tsx);
}

// registry.json (consumed by the compiler, Rust templates, and the SPA)
writeFileSync(join(out, "registry.json"), JSON.stringify(result.registry, null, 2) + "\n");

// keyframes.css (global, includes per-variant renamed conflicts)
writeFileSync(join(out, "keyframes.css"), result.keyframesCss + "\n");

// registry.ts — typed component map
const imports = result.variants
  .map((v) => `import { ${v.component} } from "./${v.collectionSlug}/${v.id}";`)
  .join("\n");
const entries = result.variants
  .map((v) => `  "${v.id}": ${v.component},`)
  .join("\n");
const registryTs = `// Auto-generated by @vexillum/converter — do not hand-edit.
import type { ComponentType } from "react";
import type { BadgeProps } from "./types";
${imports}

export const registry: Record<string, ComponentType<BadgeProps>> = {
${entries}
};

export const variantIds = Object.keys(registry);
`;
writeFileSync(join(out, "registry.ts"), registryTs);

const summary = {
  input: basename(input),
  collections: result.collections.length,
  variants: result.variants.length,
  withIcon: result.variants.filter((v) => v.hasIcon).length,
  withExtra: result.variants.filter((v) => v.hasExtra).length,
  animated: result.variants.filter((v) => v.animations.length > 0).length,
  keyframes: [...result.keyframesCss.matchAll(/@keyframes ([\w-]+)/g)].length,
};
console.log("converted:", JSON.stringify(summary));
writeFileSync(join(out, "conversion-summary.json"), JSON.stringify(summary, null, 2) + "\n");
