/**
 * Build-time compilation (spec §4): React SSR of all badge components with
 * slot markers → out/*.html, then Tailwind CLI over the compiled HTML,
 * then Rust asset emission into crates/templates.
 */
import { mkdirSync, cpSync, readFileSync, writeFileSync, rmSync, readdirSync } from "node:fs";
import { execFileSync } from "node:child_process";
import { basename, dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { createElement } from "react";
import { renderToStaticMarkup } from "react-dom/server";
import { registry, variantIds } from "@vexillum/badges";
import registryJson from "@vexillum/badges/registry.json";
import {
  LABEL_MARKER,
  VALUE_MARKER,
  EXTRA_MARKER,
  EXTRA2_MARKER,
  ICON_MARKER,
} from "@vexillum/badges/types";

const here = dirname(fileURLToPath(import.meta.url));
const outDir = resolve(here, "../../compiler/out");
const repoRoot = resolve(here, "../../..");
const cratesTemplates = join(repoRoot, "crates/templates");

interface VariantMetaJson {
  id: string;
  collection: string;
  title: string;
  hasIcon: boolean;
  hasLabel: boolean;
  hasValue: boolean;
  hasExtra: boolean;
  hasExtra2?: boolean;
  defaultIcon: string | null;
  defaultLabel: string;
  defaultValue: string;
  defaultExtra: string | null;
  defaultExtra2?: string | null;
  animations: Array<{ name: string; durationMs: number; timing: string; iteration: string }>;
}

const metaById = new Map<string, VariantMetaJson>(
  (registryJson.variants as VariantMetaJson[]).map((v) => [v.id, v]),
);

export function compileAll(): void {
  rmSync(outDir, { recursive: true, force: true });
  mkdirSync(outDir, { recursive: true });

  let count = 0;
  for (const id of variantIds) {
    const meta = metaById.get(id);
    if (!meta) throw new Error(`registry.json missing metadata for ${id}`);
    const Component = registry[id];
    if (!Component) throw new Error(`registry.ts missing component for ${id}`);

    const html = renderToStaticMarkup(
      createElement(Component, {
        label: meta.hasLabel ? LABEL_MARKER : undefined,
        value: meta.hasValue ? VALUE_MARKER : undefined,
        extra: meta.hasExtra ? EXTRA_MARKER : undefined,
        extra2: meta.hasExtra2 ? EXTRA2_MARKER : undefined,
        // icon stays undefined so the component renders <IconSlot/> → marker
        icon: undefined,
        theme: undefined,
      }),
    );
    writeFileSync(join(outDir, `${id}.html`), html);
    count++;
  }
  console.log(`compiled ${count} templates into ${outDir}`);
}

const TAILWIND_INPUT_CSS = `@import "tailwindcss";

@theme {
  --font-sans: "Inter", ui-sans-serif, system-ui, sans-serif;
  --font-mono: "JetBrains Mono", ui-monospace, monospace;
  --font-serif: "Instrument Serif", ui-serif, Georgia, serif;
}
`;

export function runTailwind(): void {
  const input = join(outDir, "input.css");
  const output = join(outDir, "tailwind.css");
  writeFileSync(input, TAILWIND_INPUT_CSS);
  const bin = resolve(here, "../node_modules/.bin/tailwindcss");
  execFileSync(bin, ["-i", input, "-o", output, "--minify", "--content", `${outDir}/*.html`], {
    stdio: "inherit",
  });
  console.log("tailwind.css emitted");
}

export function emitRust(): void {
  const assets = join(cratesTemplates, "assets");
  rmSync(assets, { recursive: true, force: true });
  mkdirSync(join(assets, "html"), { recursive: true });
  mkdirSync(join(assets, "css"), { recursive: true });

  for (const file of readdirSync(outDir)) {
    if (file.endsWith(".html")) {
      cpSync(join(outDir, file), join(assets, "html", file));
    }
  }
  cpSync(join(outDir, "tailwind.css"), join(assets, "css", "tailwind.css"));
  cpSync(resolve(here, "../../badges/src/keyframes.css"), join(assets, "css", "keyframes.css"));
  cpSync(
    resolve(here, "../../badges/src/registry.json"),
    join(assets, "registry.json"),
  );

  // embedded.rs — include_str! registry
  const lines = variantIds
    .map((id) => {
      return `    map.insert(${JSON.stringify(id)}, Template {
        id: ${JSON.stringify(id)},
        html: include_str!(concat!(env!("CARGO_MANIFEST_DIR"), "/assets/html/${id}.html")),
    });`;
    })
    .join("\n");
  const rs = `//! Auto-generated by @vexillum/compiler — do not hand-edit.
use std::collections::HashMap;

use crate::Template;

pub fn build_registry() -> HashMap<&'static str, Template> {
    let mut map = HashMap::new();
${lines}
    map
}
`;
  mkdirSync(join(cratesTemplates, "src"), { recursive: true });
  writeFileSync(join(cratesTemplates, "src", "embedded.rs"), rs);
  console.log("crates/templates assets + embedded.rs emitted");
}

export function readOut(id: string): string {
  return readFileSync(join(outDir, `${id}.html`), "utf8");
}

if (process.argv[1] && import.meta.url.endsWith(basename(process.argv[1]))) {
  const cmd = process.argv[2] ?? "all";
  if (cmd === "all") {
    compileAll();
    runTailwind();
    emitRust();
  } else if (cmd === "compile") compileAll();
  else if (cmd === "tailwind") runTailwind();
  else if (cmd === "emit") emitRust();
}
