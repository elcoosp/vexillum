/// File header for generated TS.
fn ts_header(comment: &str) -> String {
    format!(
        "// {comment}\n// Generated by crates/icons/src/bin/dump-brand-index.rs from simpleicons-rs.\n// Do not edit by hand; run `cargo run --package vexillum-icons --bin dump-brand-index`.\n"
    )
}

fn main() {
    let manifest = std::env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR");
    let root = std::path::Path::new(&manifest)
        .parent()
        .and_then(|p| p.parent())
        .expect("repo root")
        .to_path_buf();

    // 1. read the slug list (source of enumeration order)
    let raw = std::fs::read_to_string(root.join("crates/icons/assets/simple-icons-slugs.txt"))
        .expect("simple-icons-slugs.txt present");
    let slugs: Vec<&str> = raw
        .lines()
        .map(str::trim)
        .filter(|l| !l.is_empty() && !l.starts_with('#'))
        .collect();
    assert!(
        slugs.len() >= 3_000,
        "suspiciously small slug list: {}",
        slugs.len()
    );

    // 2. resolve every icon through the crate (authoritative data)
    struct Entry {
        slug: String,
        title: String,
        hex: String,
        path: String,
    }
    let mut entries: Vec<Entry> = Vec::with_capacity(slugs.len());
    let mut missing: Vec<&str> = Vec::new();
    for slug in &slugs {
        match simpleicons_rs::slug(slug) {
            Some(icon) => {
                let path = vexillum_icons::brand_path(icon)
                    .unwrap_or_else(|| panic!("{slug}: path extraction failed"));
                entries.push(Entry {
                    slug: slug.to_string(),
                    title: icon.title.to_string(),
                    hex: icon.hex.to_string(),
                    path,
                });
            }
            None => missing.push(slug),
        }
    }
    if !missing.is_empty() {
        panic!(
            "{} slugs in the list do not resolve in simpleicons-rs — regenerate simple-icons-slugs.txt: {:?}",
            missing.len(),
            &missing[..missing.len().min(10)]
        );
    }

    // 3. brands-index.json (runtime enumeration index — no path data)
    let mut json = String::from("[\n");
    for (i, e) in entries.iter().enumerate() {
        let comma = if i + 1 == entries.len() { "" } else { "," };
        writeln!(
            json,
            " {{\"slug\":{},\"title\":{},\"hex\":{}}}{comma}",
            json_str(&e.slug),
            json_str(&e.title),
            json_str(&e.hex)
        )
        .unwrap();
    }
    json.push_str("]\n");
    std::fs::write(root.join("crates/icons/assets/brands-index.json"), json).expect("write index");

    // 4. web outputs
    let eager: std::collections::HashSet<&str> = EAGER_SLUGS.iter().copied().collect();
    let web = root.join("apps/web/src/lib");

    // icon-catalog.ts — eager metadata
    let mut out =
        ts_header("Eager brand metadata (template defaults + popular core) for the preview layer.");
    out.push_str("import type { IconMeta } from \"@/lib/icon-catalog-full\";\n\n");
    out.push_str("export type { IconMeta };\n\n");
    out.push_str(
        "/** Brand icons available without a lazy chunk (the rest live in icon-catalog-full). */\n",
    );
    out.push_str("export const CURATED_ICONS: IconMeta[] = [\n");
    for e in &entries {
        if eager.contains(e.slug.as_str()) {
            writeln!(
                out,
                " {{ slug: {}, title: {}, hex: {} }},",
                json_str(&e.slug),
                json_str(&e.title),
                json_str(&e.hex)
            )
            .unwrap();
        }
    }
    out.push_str("];\n");
    std::fs::write(web.join("icon-catalog.ts"), out).expect("write icon-catalog.ts");

    // icon-catalog-full.ts — lazy full metadata
    let mut out =
        ts_header("Full Simple Icons metadata (all icons) — lazy chunk for the icon picker.");
    out.push_str(
        "export interface IconMeta {\n  slug: string;\n  title: string;\n  hex: string;\n}\n\n",
    );
    out.push_str("export const BRAND_ICONS_FULL: IconMeta[] = [\n");
    for e in &entries {
        writeln!(
            out,
            " {{ slug: {}, title: {}, hex: {} }},",
            json_str(&e.slug),
            json_str(&e.title),
            json_str(&e.hex)
        )
        .unwrap();
    }
    out.push_str("];\n");
    std::fs::write(web.join("icon-catalog-full.ts"), out).expect("write icon-catalog-full.ts");

    // icon-paths.ts — eager-popular path data
    let mut out = ts_header("Eager brand path data (template defaults + popular core).");
    out.push_str("/** Slug -> SVG path data, lazily imported by the playground/dashboard. */\n");
    out.push_str("export const ICON_PATHS: Record<string, string> = {\n");
    for e in &entries {
        if eager.contains(e.slug.as_str()) {
            writeln!(out, " {}: {},", json_str(&e.slug), json_str(&e.path)).unwrap();
        }
    }
    out.push_str("};\n");
    std::fs::write(web.join("icon-paths.ts"), out).expect("write icon-paths.ts");

    // icon-paths-full.ts — lazy full path data
    let mut out = ts_header(
        "Full Simple Icons path data (all icons) — lazy chunk for the picker and preview misses.",
    );
    out.push_str("export const ICON_PATHS_FULL: Record<string, string> = {\n");
    for e in &entries {
        writeln!(out, " {}: {},", json_str(&e.slug), json_str(&e.path)).unwrap();
    }
    out.push_str("};\n");
    std::fs::write(web.join("icon-paths-full.ts"), out).expect("write icon-paths-full.ts");

    let eager_count = entries
        .iter()
        .filter(|e| eager.contains(e.slug.as_str()))
        .count();
    println!(
        "wrote brands-index.json ({} icons; {} eager) + 4 web TS files",
        entries.len(),
        eager_count
    );
}

/// Minimal JSON string escaper (Simple Icons titles carry quotes/unicode).
fn json_str(s: &str) -> String {
    let mut out = String::with_capacity(s.len() + 2);
    out.push('"');
    for c in s.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            c if (c as u32) < 0x20 => {
                write!(out, "\\u{:04x}", c as u32).unwrap();
            }
            c => out.push(c),
        }
    }
    out.push('"');
    out
}
