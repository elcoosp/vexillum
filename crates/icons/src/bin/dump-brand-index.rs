//! Generates every Simple Icons enumeration asset from the
//! `simpleicons-rs` crate — the single source of truth for brand icons.
//!
//! Outputs:
//! - `crates/icons/assets/brands-index.json` — runtime index (slug/title/hex)
//!   embedded by `vexillum-icons` for enumeration (`/v1/icons`, pickers).
//!   Path data is NOT in here: resolve time reads it live from the crate.
//! - `apps/web/src/lib/icon-catalog.ts` — eager popular-brand metadata for
//!   the preview layer (badge.tsx / PlaygroundPage hex lookups).
//! - `apps/web/src/lib/icon-catalog-full.ts` — lazy full metadata (picker).
//! - `apps/web/src/lib/icon-paths.ts` — eager-popular path data (lazy chunk,
//!   loaded by the playground when the icon panel opens).
//! - `apps/web/src/lib/icon-paths-full.ts` — lazy full path data (picker /
//!   non-popular preview misses).
//!
//! The slug list comes from `assets/simple-icons-slugs.txt` (extracted from
//! the crate source at its pinned version). Run on version bumps:
//! `cargo run --package vexillum-icons --bin dump-brand-index`
//!
//! The `EAGER_SLUGS` set mirrors what the preview layer needs instantly:
//! every template default icon plus a popular core. Everything else resolves
//! through the lazy chunks.

