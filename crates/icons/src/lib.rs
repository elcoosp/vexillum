//! Icon system (spec §7): Simple Icons brand icons (via the `simpleicons-rs`
//! crate — the upstream dataset, not a hand-maintained copy), the icondata
//! catalog, SVG sanitization for uploads, and a SHA-256-keyed upload store.

pub mod sanitize;
pub mod store;

use serde::Deserialize;
use vexillum_core::Error;

/// One Simple Icons brand entry: enumeration metadata only. The SVG path
/// data lives in the `simpleicons-rs` crate and is read at resolve time, so
/// this index never drifts from the rendered markup.
#[derive(Debug, Clone, PartialEq, Eq, Deserialize)]
pub struct BrandIcon {
    pub slug: String,
    pub title: String,
    /// Brand color as 6-digit hex (no `#`), e.g. `181717`.
    pub hex: String,
}

/// The full Simple Icons index (slug/title/hex for every icon the crate
/// ships). Generated by `crates/icons/src/bin/dump-brand-index.rs` from the
/// `simpleicons-rs` data; a unit test re-verifies every entry against the
/// crate so a version bump cannot silently desync.
pub fn brands() -> &'static Vec<BrandIcon> {
    static BRANDS: std::sync::OnceLock<Vec<BrandIcon>> = std::sync::OnceLock::new();
    BRANDS.get_or_init(|| {
        serde_json::from_str(include_str!("../assets/brands-index.json"))
            .expect("embedded brands-index.json is valid")
    })
}

/// Extracts the single `<path d="…">` from a simpleicons-rs SVG string.
/// Simple Icons markup is always `<svg …><title>…</title><path d="…"/></svg>`.
pub fn brand_path(icon: &simpleicons_rs::Icon) -> Option<String> {
    const NEEDLE: &str = "<path d=\"";
    let start = icon.svg.find(NEEDLE)? + NEEDLE.len();
    let rest = &icon.svg[start..];
    let end = rest.find('"')?;
    Some(rest[..end].to_string())
}

/// The brand hex for a slug (6-digit, no `#`), or `None` when unknown.
pub fn brand_hex(slug: &str) -> Option<&'static str> {
    simpleicons_rs::slug(slug).map(|i| i.hex)
}

/// The brand display title for a slug, or `None` when unknown.
pub fn brand_title(slug: &str) -> Option<&'static str> {
    simpleicons_rs::slug(slug).map(|i| i.title)
}

/// The icon color modes (spec §10.2 `icon.color`).
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum IconColor {
    /// The brand's own color.
    Brand,
    /// Inherits the surrounding CSS `color`.
    Current,
    /// Any CSS color string (validated).
    Custom(String),
}

impl IconColor {
    /// Parses the query parameter form.
    ///
    /// The default (`auto`, absent) is `currentColor`: icons ride the badge's
    /// own themed ink — white on dark surfaces, dark on light ones — exactly
    /// like every other token in the semantic palette. The brand hex is a
    /// deliberate opt-in (`brand`), never the default: fixed brand colors
    /// (GitHub `#181717`, npm red, …) go invisible on the dark segments and
    /// dark-mode surfaces that themed inks handle automatically.
    pub fn parse(s: &str) -> Result<Self, Error> {
        match s {
            "auto" | "" => Ok(Self::Current),
            "brand" => Ok(Self::Brand),
            "currentColor" | "current" => Ok(Self::Current),
            other => {
                if vexillum_theme::Oklch::parse(other).is_some() {
                    Ok(Self::Custom(other.to_string()))
                } else {
                    Err(Error::BadRequest(format!("invalid icon color '{other}'")))
                }
            }
        }
    }

    fn css(&self, brand_hex: &str) -> String {
        match self {
            Self::Brand => format!("#{brand_hex}"),
            Self::Current => "currentColor".to_string(),
            Self::Custom(c) => c.clone(),
        }
    }
}

/// A resolved, render-ready inline SVG.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ResolvedIcon {
    pub svg: String,
    pub width: u32,
    pub height: u32,
}

/// Icon sources: a catalog slug (bare, `simple:<slug>`, or `icondata:<set>-<slug>`),
/// or a raw uploaded SVG referenced by its SHA-256 (`upload:<hash>`).
///
/// Bare slugs resolve against the curated brands first, then the icondata
/// catalog (`mdi-account`, `si-github`, `lu-git-branch`, …).
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum IconSpec {
    Simple(String),
    Upload(String),
}

impl IconSpec {
    /// Parses `slug` / `source:slug` query syntax.
    pub fn parse(s: &str) -> Result<Self, Error> {
        match s.split_once(':') {
            None if !s.is_empty() => Ok(Self::Simple(s.to_string())),
            None => Err(Error::BadRequest("icon must not be empty".into())),
            Some((source, slug)) => match source {
                "simple" | "brand" | "icondata" | "catalog" => Ok(Self::Simple(slug.to_string())),
                "upload" => Ok(Self::Upload(slug.to_string())),
                other => Err(Error::BadRequest(format!("unknown icon source '{other}'"))),
            },
        }
    }
}

/// Resolves a Simple Icons brand icon to a sized, colored inline SVG.
///
/// Path + hex come straight from the `simpleicons-rs` crate at resolve time
/// (the upstream dataset — nothing hand-maintained); the index asset is only
/// consulted for enumeration.
pub fn resolve_simple(slug: &str, color: &IconColor, size: u32) -> Result<ResolvedIcon, Error> {
    let brand =
        simpleicons_rs::slug(slug).ok_or_else(|| Error::UnknownIcon(format!("simple:{slug}")))?;
    let path = brand_path(brand).ok_or_else(|| Error::UnknownIcon(format!("simple:{slug}")))?;
    let svg = wrap_icon_svg(&path, &color.css(brand.hex), size);
    Ok(ResolvedIcon {
        svg,
        width: size,
        height: size,
    })
}

/// Lists curated slugs (for `/v1/icons` discovery).
pub fn curated_slugs() -> Vec<&'static str> {
    brands().iter().map(|b| b.slug.as_str()).collect()
}

/// Builds a self-contained inline SVG with explicit size + color.
pub fn wrap_icon_svg(path: &str, color: &str, size: u32) -> String {
    format!(
        r#"<svg viewBox="0 0 24 24" width="{size}" height="{size}" fill="{color}" xmlns="http://www.w3.org/2000/svg"><path d="{path}"/></svg>"#
    )
}

// ------------------------------------------------------------------ icondata

/// One icondata catalog entry (generated — see
/// `scripts/gen-icondata-catalog.py`; source: icondata 0.7.0).
#[derive(Debug, Clone, serde::Deserialize)]
pub struct CatalogEntry {
    /// Fully qualified slug: `<set>-<kebab-name>` (e.g. `mdi-account`).
    #[serde(rename = "i")]
    pub slug: String,
    /// Icon set id (`si`, `mdi`, `lu`, …).
    #[serde(rename = "s")]
    pub set: String,
    /// SVG `viewBox` (icondata icons are NOT uniformly 24×24).
    #[serde(rename = "v")]
    pub view_box: String,
    /// Inner SVG markup (path/line/circle elements, first-party data).
    #[serde(rename = "d")]
    pub data: String,
    #[serde(rename = "f", default)]
    pub fill: Option<String>,
    #[serde(rename = "st", default)]
    pub stroke: Option<String>,
    #[serde(rename = "sw", default)]
    pub stroke_width: Option<String>,
    #[serde(rename = "slc", default)]
    pub stroke_linecap: Option<String>,
    #[serde(rename = "slj", default)]
    pub stroke_linejoin: Option<String>,
}

/// Display metadata for one icondata set.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct IconSetMeta {
    pub id: &'static str,
    pub label: &'static str,
    pub count: usize,
}

const SET_LABELS: &[(&str, &str)] = &[
    ("ai", "Ant Design Icons"),
    ("bi", "BoxIcons"),
    ("bs", "Bootstrap Icons"),
    ("cg", "css.gg"),
    ("ch", "Charm"),
    ("fa", "Font Awesome"),
    ("fi", "Feather"),
    ("hi", "Heroicons"),
    ("im", "IcoMoon Free"),
    ("io", "Ionicons"),
    ("lu", "Lucide"),
    ("mdi", "Material Design Icons"),
    ("oc", "Octicons"),
    ("ri", "Remix Icon"),
    ("si", "Simple Icons"),
    ("tb", "Tabler"),
    ("ti", "Typicons"),
    ("vs", "VS Code Icons"),
    ("wi", "Weather Icons"),
];

struct Catalog {
    entries: Vec<CatalogEntry>,
    index: std::collections::HashMap<String, usize>,
    sets: Vec<IconSetMeta>,
}

fn catalog() -> &'static Catalog {
    static CATALOG: std::sync::OnceLock<Catalog> = std::sync::OnceLock::new();
    CATALOG.get_or_init(|| {
        let entries: Vec<CatalogEntry> =
            serde_json::from_str(include_str!("../assets/icondata.json"))
                .expect("embedded icondata.json is valid");
        let mut index = std::collections::HashMap::with_capacity(entries.len());
        for (i, e) in entries.iter().enumerate() {
            index.insert(e.slug.clone(), i);
        }
        let mut sets = Vec::with_capacity(SET_LABELS.len());
        for &(id, label) in SET_LABELS {
            let count = entries.iter().filter(|e| e.set == id).count();
            if count > 0 {
                sets.push(IconSetMeta { id, label, count });
            }
        }
        Catalog {
            entries,
            index,
            sets,
        }
    })
}

/// Metadata for every icondata set (for `/v1/icons` discovery + pickers).
pub fn icondata_sets() -> &'static [IconSetMeta] {
    &catalog().sets
}

/// Total number of icondata catalog icons.
pub fn icondata_total() -> usize {
    catalog().entries.len()
}

/// Looks up one icondata entry by fully qualified slug (`mdi-account`).
pub fn icondata_entry(slug: &str) -> Option<&'static CatalogEntry> {
    catalog().index.get(slug).map(|&i| &catalog().entries[i])
}

/// Resolves any catalog slug: curated brands first (brand-hex colors),
/// then the icondata catalog. Unknown slugs are a 404 `unknown-icon`.
pub fn resolve_any(slug: &str, color: &IconColor, size: u32) -> Result<ResolvedIcon, Error> {
    if brands().iter().any(|b| b.slug == slug) {
        return resolve_simple(slug, color, size);
    }
    resolve_icondata(slug, color, size)
}

/// Resolves an icondata entry to a sized, colored inline SVG.
///
/// Color semantics: stroke-based entries (fill `none` + a stroke) colorize
/// via `stroke`; all others via `fill`. `Brand` keeps the entry's own
/// attributes (defaulting to `currentColor`).
pub fn resolve_icondata(slug: &str, color: &IconColor, size: u32) -> Result<ResolvedIcon, Error> {
    let entry =
        icondata_entry(slug).ok_or_else(|| Error::UnknownIcon(format!("icondata:{slug}")))?;
    let svg = wrap_entry_svg(entry, color, size);
    Ok(ResolvedIcon {
        svg,
        width: size,
        height: size,
    })
}

/// Builds a self-contained inline SVG from a catalog entry, honoring its
/// per-icon `viewBox` and stroke attributes.
pub fn wrap_entry_svg(entry: &CatalogEntry, color: &IconColor, size: u32) -> String {
    let (fill, stroke) = match color {
        IconColor::Brand => (
            entry.fill.clone().unwrap_or_else(|| "currentColor".into()),
            entry.stroke.clone(),
        ),
        IconColor::Current => stroke_or_fill(entry, "currentColor"),
        IconColor::Custom(c) => stroke_or_fill(entry, c),
    };
    let mut attrs = format!(
        r#"viewBox="{}" width="{size}" height="{size}" xmlns="http://www.w3.org/2000/svg" fill="{fill}""#,
        entry.view_box
    );
    if let Some(st) = &stroke {
        attrs.push_str(&format!(r#" stroke="{st}""#));
    }
    for (attr, value) in [
        ("stroke-width", &entry.stroke_width),
        ("stroke-linecap", &entry.stroke_linecap),
        ("stroke-linejoin", &entry.stroke_linejoin),
    ] {
        if let Some(v) = value {
            attrs.push_str(&format!(r#" {attr}="{v}""#));
        }
    }
    format!(r#"<svg {attrs}>{}</svg>"#, entry.data)
}

fn stroke_or_fill(entry: &CatalogEntry, color: &str) -> (String, Option<String>) {
    if entry.fill.as_deref() == Some("none") && entry.stroke.is_some() {
        ("none".into(), Some(color.to_string()))
    } else {
        (color.to_string(), entry.stroke.clone())
    }
}

/// Renders an icon span wrapper (spec §7.2) around resolved svg markup.
pub fn icon_span(icon: &ResolvedIcon) -> String {
    format!(
        r#"<span style="display:inline-flex;align-items:center;width:{}px;height:{}px;flex-shrink:0">{}</span>"#,
        icon.width, icon.height, icon.svg
    )
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn curated_set_is_the_full_simpleicons_dataset() {
        let slugs = curated_slugs();
        assert!(
            slugs.len() >= 3_000,
            "simpleicons set too small: {}",
            slugs.len()
        );
        for slug in ["github", "typescript", "npm", "rust", "docker"] {
            assert!(slugs.contains(&slug), "{slug} missing from curated set");
        }
        // the index and the crate's own lookup agree on membership
        let raw = std::fs::read_to_string(concat!(
            env!("CARGO_MANIFEST_DIR"),
            "/assets/simple-icons-slugs.txt"
        ))
        .expect("slugs asset present");
        let expected: Vec<&str> = raw
            .lines()
            .filter(|l| !l.trim().is_empty() && !l.starts_with('#'))
            .collect();
        assert_eq!(
            slugs.len(),
            expected.len(),
            "index must cover every crate slug"
        );
    }

    #[test]
    fn index_entries_match_the_crate_exactly() {
        // a crate version bump (hex/title/path change) must fail here, not in
        // production: enumeration metadata is re-verifiable, path data is read
        // live from the crate.
        for brand in brands().iter() {
            let icon = simpleicons_rs::slug(&brand.slug)
                .unwrap_or_else(|| panic!("index slug {} missing from crate", brand.slug));
            assert_eq!(icon.title, brand.title, "{} title drift", brand.slug);
            assert_eq!(icon.hex, brand.hex, "{} hex drift", brand.slug);
            assert!(brand_path(icon).is_some(), "{} path extraction", brand.slug);
        }
    }

    #[test]
    fn brand_path_extracts_every_icon_in_the_crate() {
        // every slug the crate ships must yield exactly one usable path —
        // the resolve path depends on it
        let raw = std::fs::read_to_string(concat!(
            env!("CARGO_MANIFEST_DIR"),
            "/assets/simple-icons-slugs.txt"
        ))
        .expect("slugs asset present");
        let count = raw
            .lines()
            .filter(|l| !l.trim().is_empty() && !l.starts_with('#'))
            .filter(|slug| {
                simpleicons_rs::slug(slug)
                    .map(|i| brand_path(i).is_some())
                    .unwrap_or(false)
            })
            .count();
        assert!(count >= 3_000, "path extraction failed for {} icons", count);
    }

    #[test]
    fn brand_metadata_helpers() {
        assert_eq!(brand_hex("github"), Some("181717"));
        assert_eq!(brand_title("github"), Some("GitHub"));
        assert_eq!(brand_hex("no-such-brand"), None);
    }

    #[test]
    fn resolves_github_with_brand_color() {
        let icon = resolve_simple("github", &IconColor::Brand, 14).unwrap();
        assert!(icon.svg.contains("fill=\"#181717\""));
        assert!(icon.svg.contains("width=\"14\""));
        assert!(icon.svg.contains("height=\"14\""));
        assert_eq!(icon.width, 14);
    }

    #[test]
    fn resolves_with_current_color() {
        let icon = resolve_simple("rust", &IconColor::Current, 12).unwrap();
        assert!(icon.svg.contains("fill=\"currentColor\""));
    }

    #[test]
    fn resolves_with_custom_color() {
        let icon = resolve_simple("npm", &IconColor::Custom("#cb3837".into()), 14).unwrap();
        assert!(icon.svg.contains("fill=\"#cb3837\""));
    }

    #[test]
    fn unknown_slug_is_404() {
        let e = resolve_simple("no-such-brand", &IconColor::Brand, 14).unwrap_err();
        assert_eq!(e.status(), 404);
    }

    #[test]
    fn spec_parsing() {
        // bare slugs resolve against brands first, then the icondata catalog
        assert_eq!(
            IconSpec::parse("github").unwrap(),
            IconSpec::Simple("github".into())
        );
        assert_eq!(
            IconSpec::parse("mdi-account").unwrap(),
            IconSpec::Simple("mdi-account".into())
        );
        assert_eq!(
            IconSpec::parse("simple:github").unwrap(),
            IconSpec::Simple("github".into())
        );
        assert_eq!(
            IconSpec::parse("icondata:mdi-home").unwrap(),
            IconSpec::Simple("mdi-home".into())
        );
        assert_eq!(
            IconSpec::parse("upload:abc").unwrap(),
            IconSpec::Upload("abc".into())
        );
        assert!(IconSpec::parse("fonts:github").is_err());
        assert!(IconSpec::parse("").is_err());
    }

    #[test]
    fn icondata_catalog_loads_and_resolves() {
        assert!(icondata_total() > 30_000, "catalog suspiciously small");
        let sets = icondata_sets();
        assert!(sets.len() >= 19);
        assert!(sets.iter().any(|s| s.id == "mdi" && s.count > 7_000));
        // 24×24 fill icon
        let e = icondata_entry("si-github").expect("si-github in catalog");
        assert_eq!(e.set, "si");
        assert_eq!(e.view_box, "0 0 24 24");
        // stroke-based set keeps its stroke attributes
        let lu = resolve_icondata("lu-git-branch", &IconColor::Brand, 14).unwrap();
        assert!(lu.svg.contains("viewBox=\"0 0 24 24\""));
        assert!(lu.svg.contains("stroke=\"currentColor\""));
        assert!(lu.svg.contains("stroke-width=\"2\""));
        // custom color applies to the stroke for stroke-based entries
        let colored =
            resolve_icondata("lu-git-branch", &IconColor::Custom("#ff0000".into()), 14).unwrap();
        assert!(colored.svg.contains("stroke=\"#ff0000\""));
        // custom color applies to fill for fill-based entries
        let filled =
            resolve_icondata("mdi-account", &IconColor::Custom("#00ff00".into()), 12).unwrap();
        assert!(filled.svg.contains("fill=\"#00ff00\""));
        assert!(filled.svg.contains("width=\"12\""));
    }

    #[test]
    fn resolve_any_prefers_brands_then_icondata() {
        // brand slug keeps its brand hex
        let gh = resolve_any("github", &IconColor::Brand, 14).unwrap();
        assert!(gh.svg.contains("fill=\"#181717\""));
        // icondata slug resolves with currentColor default
        let mdi = resolve_any("mdi-account", &IconColor::Brand, 14).unwrap();
        assert!(mdi.svg.contains("fill=\"currentColor\""));
        // unknown → 404 unknown-icon
        let e = resolve_any("no-such-icon-anywhere", &IconColor::Brand, 14).unwrap_err();
        assert_eq!(e.status(), 404);
    }

    #[test]
    fn color_parsing() {
        // the default rides the themed ink; brand hex is opt-in
        assert_eq!(IconColor::parse("auto").unwrap(), IconColor::Current);
        assert_eq!(IconColor::parse("").unwrap(), IconColor::Current);
        assert_eq!(IconColor::parse("brand").unwrap(), IconColor::Brand);
        assert_eq!(
            IconColor::parse("currentColor").unwrap(),
            IconColor::Current
        );
        assert!(IconColor::parse("#ff0000").is_ok());
        assert!(IconColor::parse("oklch(0.6 0.2 250)").is_ok());
        assert!(IconColor::parse("not-a-color").is_err());
    }

    #[test]
    fn icon_span_wraps_with_dimensions() {
        let icon = ResolvedIcon {
            svg: "<svg/>".into(),
            width: 14,
            height: 14,
        };
        let span = icon_span(&icon);
        assert!(span.contains("width:14px"));
        assert!(span.contains("flex-shrink:0"));
    }
}
