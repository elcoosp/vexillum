/**
 * Generates the two new badge collections (c33 "stacked", c34 "stat") — 32
 * hand-authored variants — and patches the registry end to end:
 *
 *   1. writes packages/badges/src/{stacked,stat}/cNN-MM.tsx
 *   2. appends the two collections + 32 variant entries to
 *      packages/badges/src/registry.json (the compiler copies it into
 *      crates/templates/assets on the next `emit`)
 *   3. regenerates packages/badges/src/registry.ts from registry.json so the
 *      import map and the JSON can never drift
 *
 * Run: node scripts/gen-collections/main.mjs
 * Then: pnpm --filter @vexillum/compiler compile && cargo test -p vexillum-templates
 */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { emitTsx } from "./shared.mjs";
import { STACKED } from "./c33-stacked.mjs";
import { STAT } from "./c34-stat.mjs";

const here = dirname(fileURLToPath(import.meta.url));
const badgesSrc = resolve(here, "../../packages/badges/src");

const COLLECTIONS = [
  {
    id: "c33",
    slug: "stacked",
    title: "Stacked",
    description:
      "Physical depth by construction: offset layers, ghost copies, rims and inset panels give badges a paper-stack presence.",
  },
  {
    id: "c34",
    slug: "stat",
    title: "Stat",
    description:
      "Dashboard-grade KPIs: deltas, ranks, rates, odometers and receipt totals with tabular figures and trend semantics.",
  },
];

const VARIANTS = [...STACKED, ...STAT];
if (VARIANTS.length !== 32) throw new Error(`expected 32 variants, got ${VARIANTS.length}`);
for (const v of VARIANTS) {
  const expects = {
    label: v.hasLabel,
    value: v.hasValue,
    extra: v.hasExtra,
    icon: v.hasIcon,
  };
  for (const [slot, wanted] of Object.entries(expects)) {
    const present = slot === "icon" ? v.jsx.includes("{icon ?? <IconSlot />}") : v.jsx.includes(`{${slot}}`);
    if (present && !wanted) throw new Error(`${v.id}: jsx renders {${slot}} but has${slot[0].toUpperCase() + slot.slice(1)}=false`);
    if (!present && wanted) throw new Error(`${v.id}: has${slot[0].toUpperCase() + slot.slice(1)}=true but jsx never renders {${slot}}`);
  }
  Object.assign(v, { hasIcon: v.hasIcon, hasLabel: v.hasLabel, hasValue: v.hasValue, hasExtra: v.hasExtra });
}

// 1. TSX components -----------------------------------------------------------
for (const v of VARIANTS) {
  const dir = join(badgesSrc, v.slug);
  mkdirSync(dir, { recursive: true });
  writeFileSync(join(dir, `${v.id}.tsx`), emitTsx(v));
}
console.log(`wrote ${VARIANTS.length} TSX components`);

// 2. registry.json ------------------------------------------------------------
const registryPath = join(badgesSrc, "registry.json");
const registry = JSON.parse(readFileSync(registryPath, "utf8"));
const newIds = new Set(VARIANTS.map((v) => v.id));
const newCollectionIds = new Set(COLLECTIONS.map((c) => c.id));
// idempotent: replace previously generated c33/c34 entries, keep everything else
registry.collections = registry.collections.filter((c) => !newCollectionIds.has(c.id));
registry.variants = registry.variants.filter((v) => !newIds.has(v.id));
registry.collections.push(...COLLECTIONS);
registry.variants.push(
  ...VARIANTS.map((v) => ({
    id: v.id,
    collection: v.id.slice(0, 3),
    title: v.title,
    hasIcon: v.hasIcon,
    hasLabel: v.hasLabel,
    hasValue: v.hasValue,
    hasExtra: v.hasExtra,
    defaultIcon: v.defaultIcon,
    defaultLabel: v.defaultLabel,
    defaultValue: v.defaultValue,
    defaultExtra: v.defaultExtra,
    animations: [],
  })),
);
writeFileSync(registryPath, JSON.stringify(registry, null, 2) + "\n");
console.log(
  `registry.json: ${registry.collections.length} collections, ${registry.variants.length} variants`,
);

// 3. registry.ts (regenerated deterministically from registry.json) -----------
const componentName = (id) => {
  const m = id.match(/^c(\d{2})-(\d{2})$/);
  return `C${m[1]}${m[2]}`;
};
const imports = registry.variants
  .map((v) => {
    const slug = registry.collections.find((c) => c.id === v.collection).slug;
    return `import { ${componentName(v.id)} } from "./${slug}/${v.id}";`;
  })
  .join("\n");
const entries = registry.variants
  .map((v) => `  ${JSON.stringify(v.id)}: ${componentName(v.id)},`)
  .join("\n");
const registryTs = `// Auto-generated by @vexillum/converter and scripts/gen-collections — do not hand-edit.
import type { ComponentType } from "react";
import type { BadgeProps } from "./types";
${imports}

export const registry: Record<string, ComponentType<BadgeProps>> = {
${entries}
};

export const variantIds = Object.keys(registry);
`;
writeFileSync(join(badgesSrc, "registry.ts"), registryTs);
console.log(`registry.ts regenerated (${registry.variants.length} imports)`);
